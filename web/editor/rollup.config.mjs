// Bundles src/main.js and CodeMirror into ../vendor/mydsl-editor.js (one self-contained IIFE
// script that defines window.MyDSLEditor). Run `npm install && npm run build` here to rebuild
// after changing src/ or upgrading CodeMirror; the result is committed so building the C++
// binary never needs Node.
import { nodeResolve } from '@rollup/plugin-node-resolve';
import terser from '@rollup/plugin-terser';
import { readFileSync } from 'node:fs';

const versions = ['@codemirror/state', '@codemirror/view', '@codemirror/language', '@codemirror/commands', '@codemirror/search', '@codemirror/autocomplete']
  .map(name => `${name}@${JSON.parse(readFileSync(new URL(`./node_modules/${name}/package.json`, import.meta.url))).version}`);

export default {
  input: 'src/main.js',
  output: {
    file: '../vendor/mydsl-editor.js',
    format: 'iife',
    name: 'MyDSLEditor',
    sourcemap: false,
    banner: `/*! mydsl-editor: CodeMirror 6 (MIT, https://codemirror.net) bundled for the MyDSL debug page.\n * Generated by web/editor (npm run build) from ${versions.join(', ')}. Do not edit; edit web/editor/src and rebuild. */`,
  },
  plugins: [nodeResolve(), terser({ format: { comments: /^!/, ascii_only: true } })], // ascii_only: the file is embedded in a C++ source
};
